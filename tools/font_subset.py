"""Rebuild the Chinese font subsets used by the site (site/assets/fonts/noto-{sans,serif}-sc-subset.woff2).

Run it after adding Chinese text to the pages; a character missing from the subset falls back to a system font.
Inputs: the full Noto Sans SC and Noto Serif SC OpenType files (SIL Open Font License), saved as sans.otf and
serif.otf in the current directory. They are about 8 and 12 MB, so they are not committed; download them from
https://github.com/notofonts/noto-cjk (Sans/OTF/SimplifiedChinese, Serif/OTF/SimplifiedChinese).
Usage: cd <folder with sans.otf and serif.otf> && python3 <repo>/tools/font_subset.py <repo>
For the Xiyang Lou pages: the same, with `xy` as a second argument. It leaves the homepage's subsets alone, and writes noto-sans-sc-xy.woff2 (what those pages use and the base subset lacks) and noto-serif-sc-xy.woff2 (their headings and plan labels only), and site/xiyanglou/fonts.css with their unicode-range, so the homepage never loads them. Run it after any change to their Chinese text.
For the scene pages (Round 7): `scenes` as the second argument, the same way: noto-sans-sc-scenes.woff2, noto-serif-sc-scenes.woff2 and site/scenes/fonts.css, from every page under site/scenes/ and site/zh/scenes/. Run it after scripts/scenes_page.py whenever their Chinese text changed.
Needs uvx (/opt/data/.local/bin/uvx) for fonttools. Copied from the homepage round's scratch script palace_home_subset.py.
"""
import pathlib
import re
import subprocess
import sys

R = pathlib.Path(sys.argv[1])


def base_chars(name):
    out = subprocess.run(['uvx', '--from', 'fonttools[woff]', 'python', '-c', f"from fontTools.ttLib import TTFont; print(''.join(map(chr, TTFont({str(R / 'site/assets/fonts' / name)!r}).getBestCmap())))"], check=True, capture_output=True, encoding='utf-8').stdout
    return set(out)


def xy(tag='xy', files=('xiyanglou/index.html', 'zh/xiyanglou/index.html', 'xiyanglou/keyplan.svg'), css_dir='xiyanglou', what='the Xiyang Lou pages', serif_from_body=False):
    pages = ''.join((R / 'site' / f).read_text(encoding='utf-8') for f in files)
    chars = {c for c in pages if ord(c) > 0x2E7F}
    head = ''.join(re.findall(r'<(?:h1|h2)[^>]*>(.*?)</(?:h1|h2)>', pages, flags=re.S)) + ''.join(re.findall(r'<text[^>]*>([^<]*)</text>', pages))
    if serif_from_body:  # the scene pages set every name and heading in the serif
        head += ''.join(re.findall(r'<(?:h3|text)[^>]*>(.*?)</(?:h3|text)>', pages, flags=re.S))
    css = f'/* Generated by tools/font_subset.py {tag}. The characters of {what} beyond the homepage\'s subsets; a page with none of them loads neither file. */\n'
    for src, out, fam, wanted, weight in [('sans.otf', f'noto-sans-sc-{tag}.woff2', 'Noto Sans SC', chars - base_chars('noto-sans-sc-subset.woff2'), 400), ('serif.otf', f'noto-serif-sc-{tag}.woff2', 'Noto Serif SC', {c for c in head if ord(c) > 0x2E7F} - base_chars('noto-serif-sc-subset.woff2'), 500)]:
        u = ''.join(sorted(wanted))
        subprocess.run(['uvx', '--from', 'fonttools[woff]', 'pyftsubset', src, '--text=' + u, '--flavor=woff2', '--layout-features=*', '--output-file=' + str(R / 'site/assets/fonts' / out)], check=True)
        ranges = ','.join(f'U+{ord(c):X}' for c in sorted(wanted))
        css += f"@font-face {{ font-family: '{fam}'; src: url('../assets/fonts/{out}') format('woff2'); font-weight: {weight}; font-display: swap; unicode-range: {ranges}; }}\n"
        print(out, len(u), 'chars', (R / 'site/assets/fonts' / out).stat().st_size // 1024, 'kB')
    (R / 'site' / css_dir / 'fonts.css').write_text(css, encoding='utf-8')


if len(sys.argv) > 2 and sys.argv[2] == 'xy':
    xy()
    sys.exit(0)
if len(sys.argv) > 2 and sys.argv[2] == 'scenes':
    files = sorted(str(p.relative_to(R / 'site')) for d in ('scenes', 'zh/scenes') for p in (R / 'site' / d).rglob('*.html')) + ['scenes/keyplan.svg']
    xy('scenes', files, 'scenes', 'the scene pages', serif_from_body=True)
    sys.exit(0)
text = ''
for f in ['index.html', 'zh/index.html', 'reconstruction/index.html']:  # credits.html lists hundreds of titles: it falls back to the system font
    text += (R / 'site' / f).read_text(encoding='utf-8')
chars = sorted({c for c in text if ord(c) > 0x2E7F})
print(len(chars), 'chars')
u = ''.join(chars) + '，。、：；“”《》（）·'
for src, out in [('sans.otf', 'noto-sans-sc-subset.woff2'), ('serif.otf', 'noto-serif-sc-subset.woff2')]:
    subprocess.run(['uvx', '--from', 'fonttools[woff]', 'pyftsubset', src, '--text=' + u, '--flavor=woff2',
                    '--layout-features=*', '--output-file=' + str(R / 'site/assets/fonts' / out)], check=True)
